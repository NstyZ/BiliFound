'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const allowEvents = ['shortcut', 'theme-changed', 'settings-changed', 'download-toast', 'login-changed', 'player-ready', 'player-error', 'live-danmaku', 'live-fullscreen', 'video-fullscreen', 'window-state', 'update-progress', 'update-available', 'update-open', 'player-volume', 'player-rate'];

contextBridge.exposeInMainWorld('bg', {
  platform: process.platform,
  isWindows: process.platform === 'win32',

  on: (channel, cb) => {
    if (!allowEvents.includes(channel)) return;
    ipcRenderer.on(channel, (_e, value) => cb(value));
  },

  api: (endpoint) => ipcRenderer.invoke('api', endpoint),
  apiWbi: (endpoint, params) => ipcRenderer.invoke('api:wbi', { endpoint, params }),
  suggest: (term) => ipcRenderer.invoke('search:suggest', term),
  danmaku: (cid) => ipcRenderer.invoke('danmaku', cid),

  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),

  playerShow: (payload) => ipcRenderer.send('player:show', payload),
  playerTime: () => ipcRenderer.invoke('player:time'),
  playerState: () => ipcRenderer.invoke('player:state'),
  playerFormats: () => ipcRenderer.invoke('player:formats'),
  playerSubtitle: (payload) => ipcRenderer.invoke('player:subtitle', payload),
  playerFullscreen: (payload) => ipcRenderer.invoke('player:fullscreen', payload),
  popupMenu: (payload) => ipcRenderer.invoke('menu:popup', payload),
  playerQuality: (payload) => ipcRenderer.send('player:quality', payload),
  playerDanmaku: (on) => ipcRenderer.invoke('player:danmaku', on),
  playerDmStyle: (cfg) => ipcRenderer.send('player:dm-style', cfg),
  playerPanel: (name) => ipcRenderer.send('player:panel', name),
  playerCmd: (payload) => ipcRenderer.send('player:cmd', payload),
  liveInfo: (payload) => ipcRenderer.invoke('live:info', payload),
  liveDanmakuStart: (payload) => ipcRenderer.invoke('live:danmaku:start', payload),
  liveDanmakuStop: () => ipcRenderer.send('live:danmaku:stop'),
  liveDanmakuSend: (payload) => ipcRenderer.invoke('live:danmaku:send', payload),
  liveShow: (payload) => ipcRenderer.send('live:show', payload),
  liveHide: () => ipcRenderer.send('live:hide'),
  videoFormats: (payload) => ipcRenderer.invoke('video:formats', payload),
  downloadVideo: (payload) => ipcRenderer.invoke('video:download', payload),
  action: (payload) => ipcRenderer.invoke('action', payload),
  actionPage: (path, body, opts) => ipcRenderer.invoke('action:page', { path, body, json: !!(opts && opts.json) }),
  saveImage: (url) => ipcRenderer.invoke('image:save', url),
  addComment: (payload) => ipcRenderer.invoke('comment:add', payload),
  likeComment: (payload) => ipcRenderer.invoke('reply:action', payload),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  articleLike: (payload) => ipcRenderer.invoke('article:like', payload),
  emotePanel: (payload) => ipcRenderer.invoke('emote:panel', payload),
  uploadImages: (payload) => ipcRenderer.invoke('image:upload', payload),
  deleteHistory: (payload) => ipcRenderer.invoke('history:delete', payload),
  delWatchLater: (payload) => ipcRenderer.invoke('toview:del', payload),
  favFolders: () => ipcRenderer.invoke('fav:folders'),
  imSessions: () => ipcRenderer.invoke('im:sessions'),
  imMessages: (payload) => ipcRenderer.invoke('im:messages', payload),
  imSend: (payload) => ipcRenderer.invoke('im:send', payload),
  liveQualities: (payload) => ipcRenderer.invoke('live:qualities', payload),
  liveSetQuality: (payload) => ipcRenderer.invoke('live:setQuality', payload),
  liveVolume: (payload) => ipcRenderer.invoke('live:volume', payload),
  liveFullscreen: (payload) => ipcRenderer.invoke('live:fullscreen', payload),
  createDynamic: (payload) => ipcRenderer.invoke('dynamic:create', payload),
  removeDynamic: (payload) => ipcRenderer.invoke('dynamic:remove', payload),
  delComment: (payload) => ipcRenderer.invoke('comment:del', payload),
  pickBackground: () => ipcRenderer.invoke('bg:pick'),
  saveBackground: (data, ext) => ipcRenderer.invoke('bg:save', { data, ext }),
  removeBackground: (p) => ipcRenderer.invoke('bg:remove', p),
  backgroundFromUrl: (url) => ipcRenderer.invoke('bg:fromUrl', url),
  playerShot: () => ipcRenderer.invoke('player:shot'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  listDownloads: () => ipcRenderer.invoke('downloads:list'),
  deleteDownload: (name) => ipcRenderer.invoke('downloads:delete', name),
  videoState: (payload) => ipcRenderer.invoke('video:state', payload),
  playerResize: (rect) => ipcRenderer.send('player:resize', rect),
  playerHide: () => ipcRenderer.send('player:hide'),
  webShow: (payload) => ipcRenderer.send('web:show', payload),
  webHide: () => ipcRenderer.send('web:hide'),
  auxHide: () => ipcRenderer.send('aux:hide'),

  openLogin: () => ipcRenderer.send('open-login'),
  openDownloads: () => ipcRenderer.invoke('open-downloads'),
  downloadsDir: () => ipcRenderer.invoke('downloads-dir'),
  pickDownloadDir: () => ipcRenderer.invoke('downloads:pick'),
  resetDownloadDir: () => ipcRenderer.invoke('downloads:reset'),
  clearCache: () => ipcRenderer.invoke('clear-cache'),
  winControl: (cmd) => ipcRenderer.send('win-control', cmd),

  // 应用内更新
  updateInfo: () => ipcRenderer.invoke('update:version'),
  checkUpdate: (opts) => ipcRenderer.invoke('update:check', opts || {}),
  skipUpdate: (version) => ipcRenderer.invoke('update:skip', version),
  downloadUpdate: (asset) => ipcRenderer.invoke('update:download', asset),
  installUpdate: (payload) => ipcRenderer.invoke('update:install', payload),
  revealUpdate: (file) => ipcRenderer.invoke('update:reveal', file),
  winState: () => ipcRenderer.invoke('win-state'),
});
